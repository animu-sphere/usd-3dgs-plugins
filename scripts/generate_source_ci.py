"""Generate the source CI workflow from openstrata.ci.yaml with ost."""

import argparse
from pathlib import Path
import subprocess


REPO = Path(__file__).resolve().parents[1]
WORKFLOW = REPO / ".github/workflows/ost-source-ci.yml"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="check without writing")
    args = parser.parse_args()

    generated = subprocess.run(
        ["ost", "ci", "generate", "github", "--stdout"],
        cwd=REPO, check=True, stdout=subprocess.PIPE, encoding="utf-8",
    ).stdout

    # OST 0.23.20 does not expose additional artifact paths in the matrix.
    # Extend only the workspace upload; do not upload the generated assets.
    bundle, workspace_job, workspace = generated.partition("\n  pr-workspace:\n")
    upload_paths = "          path: |\n            .strata/targets/\n"
    if not workspace_job or workspace.count(upload_paths) != 1:
        raise SystemExit("OST workspace evidence step changed; review this generator")
    workspace = workspace.replace(
        upload_paths,
        upload_paths + "            build/*/tests/benchmark/benchmark-report.json\n",
    )
    workflow = (
        "# Generated by scripts/generate_source_ci.py from openstrata.ci.yaml.\n"
        + bundle.partition("\n")[2] + workspace_job + workspace
    )
    if args.check:
        if not WORKFLOW.is_file() or WORKFLOW.read_text(encoding="utf-8") != workflow:
            raise SystemExit("Source CI workflow is stale; run python scripts/generate_source_ci.py")
    else:
        WORKFLOW.write_text(workflow, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()

def header(vertex_count: int, properties: tuple[str, ...]) -> bytes:
    lines = [
        "ply",
        "format binary_little_endian 1.0",
        "comment generated by tools/generate_fixtures.py",
        f"element vertex {vertex_count}",
        *(f"property float {name}" for name in properties),
        "end_header",
        "",
    ]
    return "\n".join(lines).encode("ascii")


def pack_rows(rows: list[tuple[float, ...]]) -> bytes:
    return b"".join(struct.pack(f"<{len(row)}f", *row) for row in rows)



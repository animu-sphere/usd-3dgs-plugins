"""Generate deterministic binary PLY fixtures used by unit/integration tests.

Also writes the SuperSplat compressed PLY fixtures, and carries the in-repo
compressed encoder (`encode_compressed`) that the cross-format equivalence
generator imports. The encoder follows SplatTransform's writer
(COMPRESSED_PLY_MAPPING.md) except that it keeps source order, so a decoded
file can be compared with its source index by index.
"""

